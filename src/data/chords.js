/**
 * Look up chord data by name (handles enharmonic aliases and bass notes).
 * Returns array of voicings or null.
 */
export function getChordData(chordName) {
  // Strip bass note (e.g. G/B → G)
  const name = chordName.replace(/\/.*$/, '').trim();
  if (CHORD_DATA[name]) return CHORD_DATA[name];
  const alias = ALIASES[name];
  if (alias && CHORD_DATA[alias]) return CHORD_DATA[alias];
  return null;
}
